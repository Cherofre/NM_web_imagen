export function resolveInitialLanguage(storage: Storage | undefined | null): AppLanguage {
  try {
    const stored = storage?.getItem(LANGUAGE_STORAGE_KEY);
    if (stored === "en") return "en";
    if (stored === DEFAULT_LANGUAGE) return DEFAULT_LANGUAGE;
    const browserLanguage = typeof navigator === "undefined" ? "" : navigator.language || "";
    return browserLanguage.toLowerCase().startsWith("en") ? "en" : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function createTranslator(language: AppLanguage) {
  return (key: string, params: MessageParams = {}) => {
    const template = messages[language][key] || messages[DEFAULT_LANGUAGE][key] || key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
  };
}

export function formatUpstreamError(t: ReturnType<typeof createTranslator>, message: string) {
  const trimmed = message.trim();
  if (!trimmed) return trimmed;
  return trimmed;
}
