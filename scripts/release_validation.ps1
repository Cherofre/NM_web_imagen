function Get-ValidatedReleaseVersion {
  param([string]$RepoRoot, [string]$ExpectedVersion = "")

  $Version = (Get-Content -LiteralPath (Join-Path $RepoRoot "VERSION") -Encoding UTF8 -TotalCount 1).Trim()
  $TauriVersion = ((Get-Content -LiteralPath (Join-Path $RepoRoot "studio-web\src-tauri\tauri.conf.json") -Raw -Encoding UTF8) | ConvertFrom-Json).version
  $Cargo = Get-Content -LiteralPath (Join-Path $RepoRoot "studio-web\src-tauri\Cargo.toml") -Raw -Encoding UTF8
  if ($Cargo -notmatch '(?m)^version\s*=\s*"([^"]+)"') {
    throw "Cargo package version was not found."
  }
  $CargoVersion = $Matches[1]
  if ($Version -notmatch '^\d+\.\d+\.\d+$' -or $TauriVersion -ne $Version -or $CargoVersion -ne $Version) {
    throw "Release versions are not synchronized: VERSION=$Version, Tauri=$TauriVersion, Cargo=$CargoVersion"
  }
  if (-not [string]::IsNullOrWhiteSpace($ExpectedVersion) -and $ExpectedVersion -ne $Version) {
    throw "Release version mismatch: expected $ExpectedVersion, source version is $Version"
  }
  return $Version
}

function Resolve-ReleaseZipPath {
  param([string]$ZipPath)

  $Resolved = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($ZipPath)
  if ([System.IO.Path]::GetExtension($Resolved) -ine ".zip" -or -not (Test-Path -LiteralPath $Resolved -PathType Leaf)) {
    throw "Release ZIP was not found or is not a ZIP path: $Resolved"
  }
  return $Resolved
}

function Assert-ReleaseZipFreshness {
  param([string]$ZipPath, [string]$RepoRoot, [ValidateSet("web", "desktop-portable")][string]$Kind)

  $ZipPath = Resolve-ReleaseZipPath -ZipPath $ZipPath
  $Root = [System.IO.Path]::GetFullPath($RepoRoot).TrimEnd("\", "/")
  $Paths = @("VERSION")
  if ($Kind -eq "web") {
    $Prefix = "NM_web_imagen/"
    $Paths += @(
      "app.py", "image_safety.py", "storage.py", "upstream.py", "requirements.txt", "config.example.json",
      "start_web.ps1", "stop_web.ps1", "start_web.bat", "stop_web.bat"
    )
    # Keep this helper ASCII-only while checking the two Chinese launchers.
    $Paths += [string]::Concat([char[]]@(19968, 38190, 21551, 21160, 46, 98, 97, 116))
    $Paths += [string]::Concat([char[]]@(19968, 38190, 20572, 27490, 46, 98, 97, 116))
    foreach ($File in @(Get-ChildItem -LiteralPath (Join-Path $Root "vendor") -Recurse -File)) {
      $Paths += $File.FullName.Substring($Root.Length + 1) -replace "\\", "/"
    }
    # README is generated by package_web_tool.ps1, rather than copied from source.
    $StaticRoot = Join-Path $Root "static"
  } else {
    $Prefix = "NM Image Studio/backend/"
    $StaticRoot = Join-Path $Root "static\studio"
  }
  foreach ($File in @(Get-ChildItem -LiteralPath $StaticRoot -Recurse -File)) {
    if ($File.Extension -in @(".html", ".js", ".css")) {
      $Paths += $File.FullName.Substring($Root.Length + 1) -replace "\\", "/"
    }
  }
  if ($Paths -notcontains "static/studio/index.html") {
    throw "Current Studio frontend entry is missing."
  }
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $Zip = [System.IO.Compression.ZipFile]::OpenRead($ZipPath)
  try {
    foreach ($Relative in $Paths) {
      $Name = $Prefix + $Relative
      $Entries = @($Zip.Entries | Where-Object { ($_.FullName -replace "\\", "/") -ceq $Name })
      if ($Entries.Count -ne 1) {
        throw "Release package is stale or ambiguous: expected one current file $Name"
      }
      $Stream = $Entries[0].Open()
      $Sha = [System.Security.Cryptography.SHA256]::Create()
      try {
        $Hash = ([BitConverter]::ToString($Sha.ComputeHash($Stream))).Replace("-", "").ToLowerInvariant()
      } finally {
        $Sha.Dispose()
        $Stream.Dispose()
      }
      $SourceHash = (Get-FileHash -LiteralPath (Join-Path $Root ($Relative -replace "/", "\")) -Algorithm SHA256).Hash.ToLowerInvariant()
      if ($Hash -ne $SourceHash) {
        throw "Release package is stale: $Name differs from current source/resources. Rebuild this artifact."
      }
    }
  } finally {
    $Zip.Dispose()
  }
}
